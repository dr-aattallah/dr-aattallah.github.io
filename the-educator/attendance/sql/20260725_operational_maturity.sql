create table if not exists public.attendance_term_archives (
  archive_id bigint generated by default as identity primary key,
  term_code text not null,
  archive_status text not null default 'Completed',
  archived_at timestamptz not null default now(),
  archived_by uuid not null references auth.users(id),
  course_count integer not null,
  session_count integer not null,
  attendance_count integer not null,
  excuse_count integer not null,
  snapshot jsonb not null,
  constraint attendance_term_archive_status_check check (
    archive_status in ('Completed', 'Verified', 'Superseded')
  ),
  constraint attendance_term_archive_unique unique (term_code, archived_at)
