begin;

create table if not exists public.attendance_notifications (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.users(id) on delete cascade,
  notification_type text not null,
  title_ar text not null,
  message_ar text not null,
  related_course_code text,
  related_session_id text references public.sessions(id) on delete set null,
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  read_at timestamptz,
  constraint attendance_notifications_type_check check (
    notification_type in (
      'AttendanceChanged',
      'ExcuseAccepted',
      'ExcuseRejected',
      'ExcuseMoreInfo',
      'DenialRisk'
    )
  ),
  constraint attendance_notifications_message_check check (
    char_length(title_ar) between 2 and 120
    and char_length(message_ar) between 2 and 1000
  )
);

create index if not exists attendance_notifications_student_created_idx
  on public.attendance_notifications (student_id, created_at desc);
create index if not exists attendance_notifications_unread_idx
  on public.attendance_notifications (student_id, is_read)
  where not is_read;

alter table public.attendance_notifications enable row level security;
revoke all on public.attendance_notifications from anon, authenticated;
grant select, update on public.attendance_notifications to authenticated;

drop policy if exists attendance_notifications_student_select
  on public.attendance_notifications;
create policy attendance_notifications_student_select
  on public.attendance_notifications
  for select to authenticated
  using (
    student_id = auth.uid()
    or public.attendance_is_privileged()
  );

drop policy if exists attendance_notifications_student_update
  on public.attendance_notifications;
create policy attendance_notifications_student_update
  on public.attendance_notifications
  for update to authenticated
  using (student_id = auth.uid())
  with check (student_id = auth.uid());

create table if not exists public.attendance_retention_policies (
  data_category text primary key,
  retention_days integer not null,
  archive_before_delete boolean not null default true,
  legal_basis_ar text not null,
  is_enabled boolean not null default true,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id),
  constraint attendance_retention_days_check
    check (retention_days between 30 and 3650)
);

